"""Open a GitHub pull request for a verified flake patch."""
from __future__ import annotations

from dataclasses import dataclass

from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.config import Settings
from app.db.models import Diagnosis, Flake, Patch, Reference, Repo, Run, Verification
from app.errors import ApiError
from app.integrations.github import git_data
from app.services import github_accounts
from app.services.repos_access import PRIVATE_SOURCE, PUBLIC_SOURCE, get_visible_flake

GITHUB_SOURCES = {PUBLIC_SOURCE, PRIVATE_SOURCE}


@dataclass(frozen=True)
class PrPreview:
    can_create: bool
    disabled_reason: str | None
    owner: str | None
    name: str | None
    full_name: str | None
    branch: str | None
    title: str | None
    body: str | None
    base_branch: str | None
    scanned_sha: str | None
    default_moved: bool = False


def _test_title(test_id: str) -> str:
    return f"Fix flaky test {git_data.short_test_label(test_id)}"


def _format_rate(rate: float | None, low: float | None, high: float | None) -> str:
    if rate is None:
        return "n/a"
    pct = f"{rate * 100:.1f}%"
    if low is not None and high is not None:
        return f"{pct} (95% CI {low * 100:.1f}%–{high * 100:.1f}%)"
    return pct


def build_pr_body(
    *,
    flake: Flake,
    diagnosis: Diagnosis | None,
    verification: Verification,
    references: list[Reference],
    scanned_sha: str,
    default_branch: str,
    default_tip: str | None,
) -> str:
    lines = [
        "## Summary",
        "",
        f"**Test:** `{flake.test_id}`",
        f"**Category:** {flake.category or (diagnosis.category if diagnosis else 'unknown')}",
        "",
        "**Root cause**",
        "",
        (diagnosis.root_cause if diagnosis else "Not recorded."),
        "",
        "## Failure rate",
        "",
        f"- Before: {_format_rate(flake.rate, flake.ci_low, flake.ci_high)} "
        f"({flake.fail_count}/{flake.run_count} detect runs)",
        f"- After: {verification.failures} failures in {verification.reruns} verify reruns"
        + (
            f" (95% upper bound {verification.ub95 * 100:.1f}%)"
            if verification.ub95 is not None
            else ""
        ),
        f"- Full suite after patch: "
        f"{'passed' if verification.full_suite_passed else 'did not pass'}",
        "",
        "## Guardrails",
        "",
        "Deterministic patch checks passed (no waits, retries, skips, or weakened asserts).",
        "",
    ]
    matched = [row for row in references if row.matched]
    refs = matched or list(references)[:5]
    if refs:
        lines.extend(["## References", ""])
        for row in refs:
            title = row.title or row.url
            lines.append(f"- [{title}]({row.url})")
        lines.append("")

    lines.extend([
        f"Generated by Deflake; verified with {verification.reruns} randomized reruns.",
        "",
        f"Opened from scanned commit `{scanned_sha[:12]}`.",
    ])
    default_moved = bool(default_tip and default_tip.lower() != scanned_sha.lower())
    if default_moved:
        lines.append(
            f"The `{default_branch}` tip has moved since the scan "
            f"(now `{default_tip[:12]}`); this PR still starts from the scanned commit."
        )
    return "\n".join(lines)


async def _load_context(
    db: AsyncSession, settings: Settings, user_id: str, flake_id: str,
) -> tuple[Flake, Run, Repo, Patch, Verification, Diagnosis | None, list[Reference]]:
    flake = await get_visible_flake(db, flake_id, user_id)
    run = await db.get(Run, flake.run_id)
    if run is None:
        raise ApiError(404, "run_not_found", "Run not found.")
    repo = await db.get(Repo, run.repo_id)
    if repo is None:
        raise ApiError(404, "repo_not_found", "This repository was not found.")

    patches = list(await db.scalars(
        select(Patch).where(Patch.flake_id == flake.id).order_by(Patch.attempt.desc())
    ))
    chosen: Patch | None = None
    verification: Verification | None = None
    for patch in patches:
        check = await db.scalar(
            select(Verification).where(Verification.patch_id == patch.id)
        )
        if check is not None and check.outcome == "verified":
            chosen = patch
            verification = check
            break
    if chosen is None or verification is None:
        raise ApiError(
            409,
            "patch_not_verified",
            "Open a pull request only after a patch is verified.",
        )
    diagnosis = await db.scalar(
        select(Diagnosis).where(Diagnosis.flake_id == flake.id)
        .order_by(Diagnosis.attempt.desc())
    )
    references = list(await db.scalars(
        select(Reference).where(Reference.flake_id == flake.id)
    ))
    return flake, run, repo, chosen, verification, diagnosis, references


def _static_blockers(repo: Repo, flake: Flake, settings: Settings) -> str | None:
    if repo.source not in GITHUB_SOURCES:
        return "Pull requests are only available for imported GitHub repositories."
    if not settings.github_oauth_enabled:
        return "GitHub OAuth is turned off in this environment."
    if flake.routing and flake.routing != "auto_pr":
        return "This fix is not routed for an automatic pull request. Download the patch instead."
    if not repo.owner or not repo.name:
        return "This repository has no GitHub owner or name."
    if not repo.commit_sha:
        return "This repository has no scanned commit to open from."
    return None


async def preview_pull_request(
    db: AsyncSession, settings: Settings, user_id: str, flake_id: str,
) -> PrPreview:
    flake, _run, repo, _patch, verification, diagnosis, references = await _load_context(
        db, settings, user_id, flake_id,
    )
    branch = git_data.branch_name_for(flake.test_id, flake.id)
    title = _test_title(flake.test_id)
    static = _static_blockers(repo, flake, settings)
    if static:
        return PrPreview(
            can_create=False,
            disabled_reason=static,
            owner=repo.owner,
            name=repo.name,
            full_name=f"{repo.owner}/{repo.name}" if repo.owner and repo.name else None,
            branch=branch,
            title=title,
            body=None,
            base_branch=repo.default_branch,
            scanned_sha=repo.commit_sha,
        )

    token = await github_accounts.access_token_for_user(db, settings, user_id)
    if not token:
        return PrPreview(
            can_create=False,
            disabled_reason="Connect GitHub to open pull requests.",
            owner=repo.owner,
            name=repo.name,
            full_name=f"{repo.owner}/{repo.name}",
            branch=branch,
            title=title,
            body=None,
            base_branch=repo.default_branch,
            scanned_sha=repo.commit_sha,
        )

    try:
        perms = await git_data.fetch_permissions(token, repo.owner, repo.name)
        tip = await git_data.fetch_branch_tip(
            token, repo.owner, repo.name, perms.default_branch,
        )
    except ApiError as exc:
        if exc.code == "github_unauthorized":
            await github_accounts.mark_disconnected_on_unauthorized(db, user_id)
            return PrPreview(
                can_create=False,
                disabled_reason="GitHub connection expired. Reconnect to continue.",
                owner=repo.owner,
                name=repo.name,
                full_name=f"{repo.owner}/{repo.name}",
                branch=branch,
                title=title,
                body=None,
                base_branch=repo.default_branch,
                scanned_sha=repo.commit_sha,
            )
        raise
    finally:
        token = None

    if not perms.push:
        return PrPreview(
            can_create=False,
            disabled_reason="You need write access to this repository. Download the patch instead.",
            owner=repo.owner,
            name=repo.name,
            full_name=perms.full_name,
            branch=branch,
            title=title,
            body=None,
            base_branch=perms.default_branch,
            scanned_sha=repo.commit_sha,
        )

    default_moved = bool(tip and tip.lower() != repo.commit_sha.lower())
    body = build_pr_body(
        flake=flake,
        diagnosis=diagnosis,
        verification=verification,
        references=references,
        scanned_sha=repo.commit_sha,
        default_branch=perms.default_branch,
        default_tip=tip,
    )
    return PrPreview(
        can_create=True,
        disabled_reason=None,
        owner=repo.owner,
        name=repo.name,
        full_name=perms.full_name,
        branch=branch,
        title=title,
        body=body,
        base_branch=perms.default_branch,
        scanned_sha=repo.commit_sha,
        default_moved=default_moved,
    )


async def create_pull_request(
    db: AsyncSession, settings: Settings, user_id: str, flake_id: str,
) -> dict:
    flake, _run, repo, patch, verification, diagnosis, references = await _load_context(
        db, settings, user_id, flake_id,
    )
    static = _static_blockers(repo, flake, settings)
    if static:
        raise ApiError(403, "pr_not_allowed", static)

    token = await github_accounts.access_token_for_user(db, settings, user_id)
    if not token:
        raise ApiError(401, "github_unauthorized", "Connect GitHub to open pull requests.")

    try:
        perms = await git_data.fetch_permissions(token, repo.owner, repo.name)
        if not perms.push:
            raise ApiError(
                403,
                "github_no_push",
                "You need write access to this repository. Download the patch instead.",
            )
        tip = await git_data.fetch_branch_tip(
            token, repo.owner, repo.name, perms.default_branch,
        )
        branch = git_data.branch_name_for(flake.test_id, flake.id)
        title = _test_title(flake.test_id)
        body = build_pr_body(
            flake=flake,
            diagnosis=diagnosis,
            verification=verification,
            references=references,
            scanned_sha=repo.commit_sha or "",
            default_branch=perms.default_branch,
            default_tip=tip,
        )
        created = await git_data.create_pull_request_from_diff(
            token,
            owner=repo.owner,
            name=repo.name,
            base_commit_sha=repo.commit_sha or "",
            default_branch=perms.default_branch,
            branch=branch,
            title=title,
            body=body,
            diff=patch.diff,
        )
    except ApiError as exc:
        if exc.code == "github_unauthorized":
            await github_accounts.mark_disconnected_on_unauthorized(db, user_id)
        raise
    finally:
        token = None

    return {
        "number": created.number,
        "html_url": created.html_url,
        "branch": created.branch,
        "head_sha": created.head_sha,
        "title": title,
    }
